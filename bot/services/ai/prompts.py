def military_news_prompt(
    phase_label: str,
    archetype_guide: str,
    avoid_phrases: list[str] | None = None,
) -> str:
    """
    پرامپت خبرنویس نظامی (v1.10.6) — تولید خبر متنوع و ضدتکرار.

    تفاوت بنیادین با نسخه‌ی قبلی: اعداد و نتایج نبرد را **موتور محاسباتی**
    تعیین کرده و در «واقعیت‌ها» به مدل داده می‌شود. مدل فقط روایت می‌کند و
    اجازه ندارد عدد یا رویداد از خودش بسازد.
    """
    avoid_block = ""
    if avoid_phrases:
        joined = "، ".join(f"«{p}»" for p in avoid_phrases[:6])
        avoid_block = (
            "\n\n⛔️ این عبارات در خبرهای اخیر استفاده شده‌اند و "
            f"**نباید** تکرار شوند:\n{joined}\n"
            "واژگان و ساختار جمله را کامل عوض کن."
        )

    return (
        BASE_RULES
        + "\n\n"
        + f"""
تو خبرنگار ارشد یک کانال خبری نظامی فارسی‌زبان هستی (شبیه World Military News).

وظیفه: برای مرحله‌ی «{phase_label}» یک خبر نظامی بنویس.

📐 **سبک این خبر (اجباری):**
{archetype_guide}

⛔️ **قوانین غیرقابل‌نقض:**
۱. فقط و فقط **یک خبر واحد** بنویس — نه دو تا، نه فهرست، نه چند پاراگراف.
۲. حداکثر **۴ خط**. کوتاه‌تر بهتر است.
۳. **هیچ عددی از خودت نساز.** فقط از اعداد و نام‌های داخل «واقعیت‌ها» استفاده کن.
۴. اگر عددی در واقعیت‌ها نبود، کیفی بنویس («خسارات قابل‌توجه») نه کمّی.
۵. نام تجهیزات را همان‌طور که در واقعیت‌ها آمده بنویس (مثل F-16، S-400، Bayraktar TB2).
۶. خروجی فقط متن فارسی خبر باشد — بدون JSON، بدون تیتر جدا، بدون شماره‌گذاری.
۷. از تگ‌های HTML تلگرام فقط <b> و <i> استفاده کن (نه Markdown).
۸. اعداد حساس راهبردی را فاش نکن؛ خلاصه‌ی خبری بنویس.{avoid_block}

مثال ساختار (سبک و واژگان را کپی نکن، فقط طول و لحن را ببین):
🔴 <b>خبر فوری</b> — گزارش‌ها از فعال‌شدن سامانه‌های پدافندی در جنوب کشور حکایت دارد. جزئیات در دست بررسی است.
""".strip()
    )
